// Builds the SQL that loads casebook cases into the case library. Pure (no files), so a test can run it against the real migrations.
// The seed is safe to run again: it updates what is there, keyed by book and case name.
//
// One entry per case name, however many books it appears in: the Booth MCG copy wins, otherwise the newest book (then one that has an
// analysis, then the book's name, so the choice never depends on file order). The other books are kept as `also_in`. A case that is
// only listed (no analysis yet) is fine: it still searches and fills in the form. If the winning copy has no analysis but another copy
// does, it adopts that analysis.

const q = (s) => `'${String(s).replace(/'/g, "''")}'`;
const arr = (a) => `array[${a.map(q).join(', ')}]::text[]`;
const nul = (v) => (v === undefined || v === null || v === '' ? 'null' : q(v));

const CORE = ['book', 'school', 'year', 'name', 'caseType', 'industry'];
const ANALYSIS = ['difficulty', 'skills', 'concepts', 'summary', 'strongAnswer', 'pitfalls', 'confidence'];

/** The same case under slightly different names: "Midwest Machinery Co." and "Midwest machinery". */
export const nameKey = (name) =>
  String(name)
    .toLowerCase()
    .replace(/&/g, ' and ')
    .replace(/[^a-z0-9 ]/g, ' ')
    .replace(/\b(co|inc|corp|company|corporation|llc|ltd)\b/g, ' ')
    .replace(/\s+/g, ' ')
    .trim();

const isBooth = (c) => /booth|mcg/i.test(`${c.school} ${c.book}`);
const analysed = (c) => ANALYSIS.every((k) => c[k] !== undefined && c[k] !== null);

/** Best first: Booth MCG, then the newest book, then one with an analysis, then the book's name. */
const better = (a, b) =>
  Number(isBooth(b)) - Number(isBooth(a)) || b.year - a.year || Number(analysed(b)) - Number(analysed(a)) || a.book.localeCompare(b.book);

/** One case per name. Returns the winners (each with `alsoIn`) and which copies were dropped in favour of which. */
export function dedupe(cases) {
  const groups = new Map();
  for (const c of cases) {
    const key = nameKey(c.name);
    groups.set(key, [...(groups.get(key) ?? []), c]);
  }
  const winners = [];
  const dropped = [];
  for (const copies of groups.values()) {
    const ranked = [...copies].sort(better);
    let [winner, ...rest] = ranked;
    winner = { ...winner, alsoIn: [...new Set(rest.map((c) => c.book).filter((b) => b !== winner.book))] };
    if (!analysed(winner)) {
      const donor = rest.find(analysed);
      if (donor) {
        for (const k of [...ANALYSIS, 'notes']) if (donor[k] !== undefined) winner[k] = donor[k];
        winner.notes = `${winner.notes ? `${winner.notes} ` : ''}(Analysis from ${donor.book}.)`.trim();
      }
    }
    winners.push(winner);
    for (const loser of rest) dropped.push({ book: loser.book, name: loser.name, keptBook: winner.book, keptName: winner.name });
  }
  return { winners, dropped };
}

/** `groups` is a list of { file, cases } (one per analysis file). */
export function seedSql(groups) {
  const all = [];
  for (const { file, cases } of groups) {
    for (const c of cases) {
      for (const key of CORE) {
        if (c[key] === undefined || c[key] === null) throw new Error(`${file}: case ${c.number ?? c.name} has no ${key}`);
      }
      const have = ANALYSIS.filter((k) => c[k] !== undefined && c[k] !== null);
      if (have.length !== 0 && have.length !== ANALYSIS.length) {
        throw new Error(`${file}: case ${c.number ?? c.name} has no ${ANALYSIS.find((k) => !have.includes(k))} (an analysis is all of it or none of it)`);
      }
      all.push(c);
    }
  }
  const { winners, dropped } = dedupe(all);

  const lines = ['-- Generated by scripts/buildLibrarySeed.mjs. Do not edit; do not commit.', 'begin;', ''];
  for (const c of winners) {
    lines.push(
      `insert into public.library_cases (book, school, year, number, name, firm, case_type, industry, cochair_pick, also_in) values (${q(c.book)}, ${q(c.school)}, ${Number(c.year)}, ${c.number ?? 'null'}, ${q(c.name)}, ${nul(c.firm)}, ${q(c.caseType)}, ${q(c.industry)}, ${c.cochairPick ? 'true' : 'false'}, ${arr(c.alsoIn)})`,
      `  on conflict (book, name) do update set school = excluded.school, year = excluded.year, number = excluded.number, firm = excluded.firm, case_type = excluded.case_type, industry = excluded.industry, cochair_pick = excluded.cochair_pick, also_in = excluded.also_in;`,
    );
    if (analysed(c)) {
      lines.push(
        `insert into public.library_case_notes (case_id, difficulty, skills, concepts, summary, strong_answer, pitfalls, confidence, notes)`,
        `  select id, ${Number(c.difficulty)}, ${arr(c.skills)}, ${arr(c.concepts)}, ${q(c.summary)}, ${q(c.strongAnswer)}, ${arr(c.pitfalls)}, ${q(c.confidence)}, ${q(c.notes ?? '')}`,
        `  from public.library_cases where book = ${q(c.book)} and name = ${q(c.name)}`,
        `  on conflict (case_id) do update set difficulty = excluded.difficulty, skills = excluded.skills, concepts = excluded.concepts, summary = excluded.summary, strong_answer = excluded.strong_answer, pitfalls = excluded.pitfalls, confidence = excluded.confidence, notes = excluded.notes, updated_at = now();`,
      );
    }
    lines.push('');
  }

  // A copy loaded by an earlier run that has since lost to a better one: move any case a member linked to it over to the winner, then remove it.
  for (const d of dropped) {
    lines.push(
      `update public.cases set library_id = (select id from public.library_cases where book = ${q(d.keptBook)} and name = ${q(d.keptName)})`,
      `  where library_id in (select id from public.library_cases where book = ${q(d.book)} and name = ${q(d.name)});`,
      `delete from public.library_cases where book = ${q(d.book)} and name = ${q(d.name)};`,
    );
  }
  // Link the cases members have already logged to what was just loaded: only a case that has the same name AND names the book, and only
  // the link, nothing else about the case. Cases that are less certain are left for each member to review.
  lines.push('select public.link_cases_to_library();', '', 'commit;', '');
  return { sql: lines.join('\n'), count: winners.length, dropped };
}
